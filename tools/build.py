#!/usr/bin/env python3
"""Builds the MorvaneOS labwc defaults.

    python tools/build.py

Needs only Python. Output goes to labwc/; commit it, it's what the package installs.

labwc reads ~/.config/labwc, then the other XDG config directories, and nothing owns
/etc/xdg/labwc, so the package installs its defaults there. labwc fills in its
built-in defaults (key bindings included) for anything rc.xml leaves out, so rc.xml
only chooses the theme. The window theme itself is morvane-gtk-theme's Openbox-format
one (/usr/share/themes/MorvaneOS-Dark/openbox-3/themerc), which labwc reads.
"""

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

THEME = 'MorvaneOS-Dark'
WALLPAPER = '/usr/share/backgrounds/morvaneos/twilight.png'

RC_XML = f'''\
<?xml version="1.0"?>
<!-- MorvaneOS defaults for labwc: generated by tools/build.py in morvane-labwc-theme, edit that instead.
     labwc's built-in defaults apply to everything not set here. -->
<labwc_config>
  <theme>
    <name>{THEME}</name>
    <cornerRadius>8</cornerRadius>
    <font place="ActiveWindow"><name>sans</name><size>10</size><weight>bold</weight></font>
    <font place="InactiveWindow"><name>sans</name><size>10</size></font>
  </theme>
</labwc_config>
'''

AUTOSTART = f'''\
# MorvaneOS: generated by tools/build.py in morvane-labwc-theme, edit that instead.
swaybg -i {WALLPAPER} -m fill >/dev/null 2>&1 &
'''


def build() -> None:
	out = ROOT / 'labwc'
	shutil.rmtree(out, ignore_errors=True)
	out.mkdir()
	(out / 'rc.xml').write_text(RC_XML)
	(out / 'autostart').write_text(AUTOSTART)
	print('Built the labwc defaults.')


if __name__ == '__main__':
	build()
